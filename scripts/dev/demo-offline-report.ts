import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { DatabaseManager } from '../../src-ts-v2/database/connection.js';
import { EntityRepository } from '../../src-ts-v2/database/EntityRepository.js';
import { PlaylistItemRepository } from '../../src-ts-v2/database/PlaylistItemRepository.js';
import { PlaylistRepository } from '../../src-ts-v2/database/PlaylistRepository.js';
import { TranscriptRepository } from '../../src-ts-v2/database/TranscriptRepository.js';
import { VideoRepository } from '../../src-ts-v2/database/VideoRepository.js';
import { HTMLReportGenerator } from '../../src-ts-v2/reports/HTMLReportGenerator.js';
import { asPlaylistId, asVideoId } from '../../src-ts-v2/types/index.js';

const workspace = mkdtempSync(join(tmpdir(), 'metube-offline-'));
const db = new DatabaseManager(join(workspace, 'library.db'));
try {
  const playlistId = asPlaylistId('PLTideNotebook');
  const captioned = asVideoId('tidalDemo01');
  const videos = [
    { video_id: captioned, title: 'Reading the Tide Clock' },
    { video_id: asVideoId('tidalDemo02'), title: 'Surveying Glass Bay' },
  ];
  db.withTransaction(() => {
    new PlaylistRepository(db).createOrUpdate({
      playlistId,
      title: 'The Tide Notebook',
      videoCount: videos.length,
    });
    const videoRepo = new VideoRepository(db);
    const items = new PlaylistItemRepository(db);
    for (const [position, video] of videos.entries()) {
      videoRepo.createOrUpdate({
        ...video,
        channel_id: 'UCGlassBayFieldStation',
        channel_title: 'Glass Bay Field Station',
        published_at: '2025-01-01T12:00:00Z',
        duration: 'PT2M',
        duration_seconds: 120,
      });
      items.addVideoToPlaylist(playlistId, video.video_id, position);
    }
    const text = 'The brass float marks the high tide.';
    new TranscriptRepository(db).upsert(captioned, {
      fullText: text,
      segments: [{ start: 0, text }],
      language: 'en',
      isAutoGenerated: false,
    });
    new EntityRepository(db).insertMany(captioned, [
      { type: 'topic', value: 'Tide gauges' },
      { type: 'topic', value: 'Coastal surveying' },
    ]);
  });

  const generator = new HTMLReportGenerator(db, {
    templatesDir: fileURLToPath(new URL('../../templates/', import.meta.url)),
    offline: true,
  });
  const playlist = await generator.generatePlaylistReport(playlistId, join(workspace, 'reports'));
  process.stdout.write(`${pathToFileURL(playlist).href}\n`);
} finally {
  db.close();
}
